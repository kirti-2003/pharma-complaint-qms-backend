    def create_error_message(
        self,
        db: Session,
        complaint_id: UUID,
        message_text: str,
        message_metadata: Optional[dict] = None,
    ) -> ComplaintMessage:
        """
        Create a system error message for the complaint conversation.
        """

        message = ComplaintMessage(
            complaint_id=complaint_id,
            sender_type="SYSTEM",
            message_type="ERROR",
            message_text=message_text,
            message_metadata=message_metadata or {},
        )

        db.add(message)
        db.flush()
        db.refresh(message)

        return message

    def count_messages_by_complaint_id(
        self,
        db: Session,
        complaint_id: UUID,
    ) -> int:
        """
        Count all messages belonging to a complaint.
        """

        return (
            db.query(ComplaintMessage)
            .filter(
                ComplaintMessage.complaint_id == complaint_id
            )
            .count()
        )

    def message_belongs_to_complaint(
        self,
        db: Session,
        message_id: UUID,
        complaint_id: UUID,
    ) -> bool:
        """
        Check whether a message belongs to a specific complaint.
        """

        message = (
            db.query(ComplaintMessage.message_id)
            .filter(
                ComplaintMessage.message_id == message_id,
                ComplaintMessage.complaint_id == complaint_id,
            )
            .first()
        )

        return message is not None

    def delete_message(
        self,
        db: Session,
        message: ComplaintMessage,
    ) -> None:
        """
        Delete a message record.

        The service layer should allow this only while the complaint
        is still an uncommitted draft.
        """

        db.delete(message)
        db.flush()